// b²c build. `node build.mjs [--release] [--out dir] [--watch]`
//
// 1. generates src/features/index.gen.ts from the feature folders
// 2. bundles content scripts (IIFE), service worker and UI (ESM) with esbuild
// 3. assembles content.css (tokens + base + every feature's style.css) and
//    checks that every rule is gated by an html[data-b2c-*] attribute
// 4. writes manifest.json, schema.json (also to dev/schema.json for Design),
//    build-id.txt, the UI pages and icons

