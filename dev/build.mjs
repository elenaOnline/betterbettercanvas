import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { deflateSync } from 'node:zlib';

const DEV = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.dirname(DEV);
const args = process.argv.slice(2);
const release = args.includes('--release');
const watch = args.includes('--watch');
const outIdx = args.indexOf('--out');
const OUT = path.resolve(DEV, outIdx >= 0 ? args[outIdx + 1] : 'dist');
const pkg = JSON.parse(fs.readFileSync(path.join(DEV, 'package.json'), 'utf8'));
// B2C_FEATURES=a,b builds only those features (parallel build lanes use this
// with their own --out so a half-written feature elsewhere can't break them).
const only = process.env.B2C_FEATURES ? new Set(process.env.B2C_FEATURES.split(',').map(x => x.trim())) : null;

const rd = p => fs.readFileSync(p, 'utf8');
const wr = (p, s) => {
  fs.mkdirSync(path.dirname(p), { recursive: true });
  fs.writeFileSync(p, s);
};

// ── 1. feature index ────────────────────────────────────────────────────────
export function genFeatureIndex() {
  const dir = path.join(DEV, 'src/features');
  const ids = fs
    .readdirSync(dir, { withFileTypes: true })
    .filter(d => d.isDirectory() && fs.existsSync(path.join(dir, d.name, 'index.ts')))
    .map(d => d.name)
    .sort();
  const p = path.join(dir, 'index.gen.ts');
  const src = featureIndexSource(ids);
  // The file on disk always lists every feature (typecheck, vitest). Bundles
  // get a virtual copy filtered by B2C_FEATURES (see featurePlugin).
  if (!only && (!fs.existsSync(p) || rd(p) !== src)) wr(p, src);
  return only ? ids.filter(id => only.has(id)) : ids;
}

// B2C_TEST_FEATURES=1 adds test/features/* (lifecycle probes) to a build.
const testFeatures = () =>
  process.env.B2C_TEST_FEATURES ? fs.readdirSync(path.join(DEV, 'test/features')).filter(d => fs.existsSync(path.join(DEV, 'test/features', d, 'index.ts'))) : [];

/** Features with a lazily loaded runtime (src/features/<id>/run.ts). */
export const lazyIds = ids => ids.filter(id => fs.existsSync(path.join(DEV, 'src/features', id, 'run.ts')));

function featureIndexSource(ids, extra = [], { lazy = false, sheets = [] } = {}) {
  const ident = id => '_' + id.replace(/-/g, '_');
  const all = [...ids, ...extra];
  // Bundles (lazy=true) wrap features that have run.ts so their runtime is a
  // separate chunk, and name each feature's split stylesheet (css/<id>.css);
  // the checked-in file (typecheck, vitest) stays plain.
  const wrapped = new Set(lazy ? lazyIds(ids) : []);
  const styled = new Set(lazy ? sheets : []);
  const def = id => (styled.has(id) ? `withStylesheet(${ident(id)}, 'css/${id}.css')` : ident(id));
  const ref = id => (wrapped.has(id) ? `lazyRuntime(${def(id)}, 'chunks/${id}.js')` : def(id));
  const helpers = [...(wrapped.size ? ['lazyRuntime'] : []), ...(styled.size ? ['withStylesheet'] : [])];
  return (
    '// Generated by build.mjs from the folders in src/features. Do not edit.\n' +
    "import type { AnyFeature } from '../core/feature.ts';\n" +
    (helpers.length ? `import { ${helpers.join(', ')} } from '../core/feature.ts';\n` : '') +
    ids.map(id => `import ${ident(id)} from './${id}/index.ts';`).join('\n') + '\n' +
    extra.map(id => `import ${ident(id)} from '../../test/features/${id}/index.ts';`).join('\n') +
    `\n\nexport const features: readonly AnyFeature[] = [${[...ids.map(ref), ...extra.map(ident)].join(', ')}] as AnyFeature[];\n`
  );
}

const featurePlugin = (ids, sheets = []) => ({
  name: 'b2c-features',
  setup(b) {
    b.onLoad({ filter: /src[\\/]features[\\/]index\.gen\.ts$/ }, () => ({
      contents: featureIndexSource(ids, testFeatures(), { lazy: true, sheets }),
      loader: 'ts',
      resolveDir: path.join(DEV, 'src/features'),
    }));
  },
});

// ── 3. CSS ──────────────────────────────────────────────────────────────────
/** Split a selector list on top-level commas (not inside (), [] or quotes). */
function splitSelectors(list) {
  const out = [];
  let depth = 0, quote = null, cur = '';
  for (const ch of list) {
    if (quote) {
      if (ch === quote) quote = null;
    } else if (ch === '"' || ch === "'") quote = ch;
    else if (ch === '(' || ch === '[') depth++;
    else if (ch === ')' || ch === ']') depth--;
    else if (ch === ',' && depth === 0) {
      out.push(cur.trim());
      cur = '';
      continue;
    }
    cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

/** Returns a list of ungated selectors (empty = fine). */
export function lintGating(css, file) {
  const bad = [];
  const s = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let depth = 0, start = 0;
  const skipStack = []; // depths at which we're inside @keyframes / @font-face
  const ruleStack = []; // depths of open style rules (CSS nesting)
  for (let i = 0; i < s.length; i++) {
    const ch = s[i];
    if (ch === '{') {
      const prelude = s.slice(start, i).trim();
      const inSkip = skipStack.length > 0;
      // Nested inside a style rule: gated by its (already checked) parent.
      const nested = ruleStack.length > 0;
      if (!inSkip && !nested && prelude && !prelude.startsWith('@')) {
        for (const sel of splitSelectors(prelude)) {
          if (!/^html\[data-b2c[\w-]*(?:[~|^$*]?=\s*"[^"]*")?\]/.test(sel)) bad.push(`${file}: ${sel}`);
        }
      }
      if (/^@(-\w+-)?(keyframes|font-face|property)/.test(prelude)) skipStack.push(depth);
      else if (prelude && !prelude.startsWith('@')) ruleStack.push(depth);
      depth++;
      start = i + 1;
    } else if (ch === '}') {
      depth--;
      if (skipStack.length && skipStack[skipStack.length - 1] === depth) skipStack.pop();
      if (ruleStack.length && ruleStack[ruleStack.length - 1] === depth) ruleStack.pop();
      start = i + 1;
    } else if (ch === ';') {
      start = i + 1;
    }
  }
  return bad;
}

// Split stylesheets (lane css-split, board/decisions.md): content.css keeps
// only core (Design's tokens, core UI such as the side panel); each feature's
// layers become css/<id>.css, registered by the service worker only while the
// feature can apply (src/background/css.ts). B2C_CSS_SPLIT=0 builds the old
// single content.css (for before/after measurements).
const SPLIT = process.env.B2C_CSS_SPLIT !== '0';

/** A feature's stylesheet layers, in cascade order. */
function featureLayers(id) {
  const out = [];
  // Design's own sheet for a surface, used as-is so Design can iterate
  // without copying; then the feature's style.css (overrides/glue).
  // Generated layers first (e.g. palette's literals.gen.css), so Design's
  // hand rules and the feature's glue win ties.
  const fdir = path.join(DEV, 'src/features', id);
  for (const g of fs.existsSync(fdir) ? fs.readdirSync(fdir).filter(f => f.endsWith('.gen.css')).sort() : []) {
    out.push([`src/features/${id}/${g}`, rd(path.join(fdir, g))]);
  }
  // A renamed feature keeps Design's sheet until Design renames it.
  const DESIGN_ALIAS = { palette: 'dark-mode' };
  const dn = fs.existsSync(path.join(ROOT, 'design/spec/surfaces', `${id}.css`)) ? id : DESIGN_ALIAS[id] ?? id;
  const d = path.join(ROOT, 'design/spec/surfaces', `${dn}.css`);
  if (fs.existsSync(d)) out.push([`design/spec/surfaces/${dn}.css`, rd(d)]);
  const p = path.join(DEV, 'src/features', id, 'style.css');
  if (fs.existsSync(p)) out.push([`src/features/${id}/style.css`, rd(p)]);
  return out;
}

/** The custom property a split sheet sets on <html>, so a page can tell it is present. */
export const sheetMarker = id => `--b2c-css-${id}`;

/**
 * content.css (core) and, when split, one sheet per feature with CSS. Every
 * rule is gated by an html[data-b2c*] attribute (lintGating); each split sheet
 * starts with its presence marker.
 */
export function buildCss(ids, split = SPLIT) {
  const core = [];
  const tokens = path.join(ROOT, 'design/spec/tokens.css');
  if (fs.existsSync(tokens)) core.push(`/* design/spec/tokens.css */\n${rd(tokens)}`);
  const base = ['src/content/base.css', rd(path.join(DEV, 'src/content/base.css'))];
  const layers = ids.map(id => [id, featureLayers(id)]).filter(([, l]) => l.length);
  const bad = [base, ...layers.flatMap(([, l]) => l)].flatMap(([f, css]) => lintGating(css, f));
  if (bad.length) throw new Error('Ungated CSS (every rule must start with html[data-b2c…]):\n  ' + bad.join('\n  '));
  const text = l => l.map(([f, css]) => `/* ${f} */\n${css}`).join('\n');
  core.push(text([base]));
  if (!split) return { core: [...core, ...layers.map(([, l]) => text(l))].join('\n'), sheets: {} };
  const sheets = Object.fromEntries(layers.map(([id, l]) => [id, `/* b²c ${id} */\nhtml[data-b2c]{${sheetMarker(id)}:1}\n${text(l)}`]));
  return { core: core.join('\n'), sheets };
}

// ── 4. manifest, schema, icons ──────────────────────────────────────────────
// New Quizzes hosts: b²c never loads there. Keep in step with isQuizHost
// (src/core/hosts.ts), which keeps feature sheets off them.
const QUIZ_FRAME_GLOBS = ['*://*quiz-lti*', '*://*quiz-api*', '*://*.quiz.*instructure.com/*'];

function manifest(version, darkInstui = false, docsScript = false) {
  // Any Instructure-hosted Canvas; custom school domains are granted at
  // runtime (features/sites). Test builds may pre-grant hosts so e2e can
  // exercise the custom-domain path without a permission dialog.
  const matches = ['https://*.instructure.com/*'];
  const testGrants = process.env.B2C_TEST_GRANT ? process.env.B2C_TEST_GRANT.split(',').map(o => o.trim() + '/*') : [];
  return {
    manifest_version: 3,
    name: release ? 'b²c' : 'b²c (dev)',
    short_name: 'b²c',
    description: 'betterbettercanvas: Canvas, but better.',
    version,
    key: rd(path.join(DEV, 'static/manifest-key.txt')).trim(),
    minimum_chrome_version: '120',
    icons: { 16: 'icons/16.png', 32: 'icons/32.png', 48: 'icons/48.png', 128: 'icons/128.png' },
    action: { default_popup: 'popup.html', default_title: 'b²c', default_icon: { 16: 'icons/16.png', 32: 'icons/32.png' } },
    options_page: 'options.html',
    background: { service_worker: 'sw.js', type: 'module' },
    permissions: ['storage', 'scripting', 'alarms', 'activeTab', 'declarativeContent'],
    host_permissions: [...matches, ...testGrants],
    optional_host_permissions: ['https://*/*'],
    // Fonts for custom-font on any Canvas origin, including granted custom
    // domains; dynamic URLs keep the extension unfingerprintable.
    web_accessible_resources: [
      { resources: ['fonts/*.woff2'], matches: ['https://*/*'], use_dynamic_url: true },
      // Lazy feature chunks import shared chunks by *relative* URL, which
      // resolves against the static extension id, so dynamic URLs would block
      // them. Trade-off (board/decisions.md): a page could probe for b²c.
      // https://*/* because granted custom-domain schools load chunks too.
      { resources: ['chunks/*.js'], matches: ['https://*/*'], use_dynamic_url: false },
    ],
    content_scripts: [
      // Pre-paint state in every same-origin frame too (the RCE editor is an
      // about:blank/srcdoc frame): boot.js follows the top page live there.
      // In cross-origin frames (LTI tools, New Quizzes) boot finds no mirror and
      // can't reach the parent, so nothing applies; content.css stays inert.
      // New Quizzes runs in quiz-lti / quiz-api frames on *.instructure.com:
      // quiz-safe-mode means b²c never loads there (not even inert CSS).
      { matches, exclude_globs: QUIZ_FRAME_GLOBS, js: ['boot.js'], css: ['content.css'], run_at: 'document_start', all_frames: true, match_about_blank: true, match_origin_as_fallback: true },
      { matches, exclude_globs: QUIZ_FRAME_GLOBS, js: ['main.js'], run_at: 'document_start' },
      // dark-mode layer (c): InstUI literals → switchable vars, before Canvas's scripts.
      ...(darkInstui ? [{ matches, exclude_globs: QUIZ_FRAME_GLOBS, js: ['dark-instui.js'], run_at: 'document_start', world: 'MAIN' }] : []),
      { matches, exclude_globs: QUIZ_FRAME_GLOBS, js: ['env-main.js'], run_at: 'document_end', world: 'MAIN' },
      // "Documents in dark mode" (DocViewer frames on canvadocs*.instructure.com).
      // Exits at once on every other host.
      ...(docsScript ? [{ matches: ['https://*.instructure.com/*'], exclude_globs: QUIZ_FRAME_GLOBS, js: ['docs.js'], run_at: 'document_start', all_frames: true }] : []),
    ],
  };
}

async function writeSchema(outFile, ids, sheetIds = []) {
  const tmp = path.join(DEV, '.scratch', `schema-${process.pid}.mjs`);
  await esbuild.build({
    stdin: {
      contents: `import { schema } from './src/core/registry.ts';
                 import { describe } from './src/core/settings/schema.ts';
                 export default Object.fromEntries(Object.entries(schema).map(([k, s]) => [k, describe(s)]));`,
      resolveDir: DEV,
      loader: 'ts',
    },
    bundle: true,
    format: 'esm',
    platform: 'node',
    outfile: tmp,
    logLevel: 'silent',
    plugins: [featurePlugin(ids, sheetIds)],
  });
  const mod = await import(pathToFileURL(tmp).href + `?t=${Date.now()}`);
  fs.rmSync(tmp);
  const json = JSON.stringify({ generated: 'by dev/build.mjs, do not edit', settings: mod.default }, null, 2) + '\n';
  wr(outFile, json);
  if (!only) wr(path.join(DEV, 'schema.json'), json);
  return mod.default;
}

/** Placeholder icon (solid rounded square) until Design supplies real ones. */
function png(size, off = false) {
  // Placeholder until Design supplies icons. Square styling (the owner): a 2px
  // corner at 16px, scaled. "off" = grey with a dot: a Canvas tab b²c can't reach.
  const [r, g, b] = off ? [0x8a, 0x8f, 0x96] : [0x2b, 0x4c, 0x7e];
  const rad = size * 0.125;
  const dot = { cx: size * 0.78, cy: size * 0.22, r: size * 0.2 };
  const raw = Buffer.alloc((size * 4 + 1) * size);
  for (let y = 0; y < size; y++) {
    raw[y * (size * 4 + 1)] = 0;
    for (let x = 0; x < size; x++) {
      const dx = Math.max(rad - x - 0.5, x + 0.5 - (size - rad), 0);
      const dy = Math.max(rad - y - 0.5, y + 0.5 - (size - rad), 0);
      const a = Math.max(0, Math.min(1, rad - Math.hypot(dx, dy) + 0.5));
      // The dot: a small square (square styling), amber, top-right.
      const inDot = off && Math.abs(x + 0.5 - dot.cx) <= dot.r && Math.abs(y + 0.5 - dot.cy) <= dot.r;
      raw.set(inDot ? [0xe8, 0xa3, 0x17, 255] : [r, g, b, Math.round(a * 255)], y * (size * 4 + 1) + 1 + x * 4);
    }
  }
  const crcTable = Array.from({ length: 256 }, (_, n) => {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    return c >>> 0;
  });
  const crc = buf => {
    let c = 0xffffffff;
    for (const x of buf) c = crcTable[(c ^ x) & 0xff] ^ (c >>> 8);
    return (c ^ 0xffffffff) >>> 0;
  };
  const chunk = (type, data) => {
    const len = Buffer.alloc(4);
    len.writeUInt32BE(data.length);
    const td = Buffer.concat([Buffer.from(type), data]);
    const c = Buffer.alloc(4);
    c.writeUInt32BE(crc(td));
    return Buffer.concat([len, td, c]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr.set([8, 6, 0, 0, 0], 8);
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw)),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

function writeIcons() {
  for (const s of [16, 32, 48, 128]) {
    const designed = path.join(DEV, 'static/icons', `${s}.png`);
    const dst = path.join(OUT, 'icons', `${s}.png`);
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    if (fs.existsSync(designed)) fs.copyFileSync(designed, dst);
    else fs.writeFileSync(dst, png(s));
    const designedOff = path.join(DEV, 'static/icons', `off-${s}.png`);
    const dstOff = path.join(OUT, 'icons', `off-${s}.png`);
    if (fs.existsSync(designedOff)) fs.copyFileSync(designedOff, dstOff);
    else fs.writeFileSync(dstOff, png(s, true));
  }
}

