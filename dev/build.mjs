// ── 2. bundle + assemble ────────────────────────────────────────────────────
export async function build() {
  const t0 = performance.now();
  const ids = genFeatureIndex();
  const css = buildCss(ids);
  const sheetIds = Object.keys(css.sheets);
  const buildId = `${pkg.version}+${new Date().toISOString().replace(/[-:]/g, '').slice(0, 15)}${release ? '' : '.dev'}`;
  // Chrome's version must be 1–4 dot-separated integers.
  const version = pkg.version;
  const define = { __B2C_BUILD_ID__: JSON.stringify(buildId), __B2C_RELEASE__: String(release), __B2C_FEATURE_IDS__: JSON.stringify([...ids, ...testFeatures()]), __B2C_TEST__: String(!!process.env.B2C_TEST_FEATURES && !release), __B2C_SHEETS__: JSON.stringify(sheetIds) };
  const common = { plugins: [featurePlugin(ids, sheetIds)], bundle: true, target: 'chrome120', define, logLevel: 'warning', legalComments: 'none', minify: release, sourcemap: release ? false : 'inline' };

  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });

  const agentRun = fs.existsSync(path.join(DEV, 'src/core/agent/run.ts'));
  await Promise.all([
    // `import css from './widget.css'` gives text (for shadow-root widgets).
    esbuild.build({ ...common, format: 'iife', entryPoints: { boot: 'src/content/boot.ts', main: 'src/content/main.ts', 'env-main': 'src/content/env-main.ts', ...(ids.includes('dark-mode') ? { 'dark-instui': 'src/features/dark-mode/instui-main.ts' } : {}), ...(ids.includes('palette') && fs.existsSync(path.join(DEV, 'src/features/palette/instui-main.ts')) ? { 'dark-instui': 'src/features/palette/instui-main.ts' } : {}), ...(ids.includes('palette') && fs.existsSync(path.join(DEV, 'src/features/palette/docs.ts')) ? { docs: 'src/features/palette/docs.ts' } : {}) }, outdir: OUT, absWorkingDir: DEV, loader: { '.css': 'text' } }),
    esbuild.build({ ...common, format: 'esm', entryPoints: { sw: 'src/background/sw.ts' }, outdir: OUT, absWorkingDir: DEV }),
    // Agent kit (agentkit/ `b2c check`): the theme engine as a plain Node ESM
    // module, so its checks run the same code as Import. Dev builds only.
    ...(!release && fs.existsSync(path.join(DEV, 'src/core/theme/node.ts'))
      ? [esbuild.build({ plugins: [featurePlugin(ids, sheetIds)], bundle: true, platform: 'node', format: 'esm', target: 'node20', define, logLevel: 'warning', entryPoints: { 'agent/theme': 'src/core/theme/node.ts' }, outExtension: { '.js': '.mjs' }, outdir: OUT, absWorkingDir: DEV, loader: { '.css': 'text' } })]
      : []),
    // Feature runtimes (run.ts) as lazily imported ESM chunks; shared code is
    // split out once, so core helpers (toast, side panel…) stay singletons
    // across feature chunks.
    // The agent describe runtime (core/agent/run.ts) rides along as
    // chunks/agent.js, loaded only when an agent asks; `agent` is a reserved
    // feature id, so it can't collide.
    ...(lazyIds(ids).length || agentRun
      ? [esbuild.build({ ...common, sourcemap: false, format: 'esm', splitting: true, entryPoints: { ...Object.fromEntries(lazyIds(ids).map(id => [id, `src/features/${id}/run.ts`])), ...(agentRun ? { agent: 'src/core/agent/run.ts' } : {}) }, entryNames: 'chunks/[name]', chunkNames: 'chunks/shared-[hash]', outdir: OUT, absWorkingDir: DEV, loader: { '.css': 'text' } })]
      : []),
    esbuild.build({ ...common, format: 'esm', entryPoints: { popup: 'src/ui/popup/popup.tsx', options: 'src/ui/options/options.tsx' }, outdir: OUT, absWorkingDir: DEV, jsx: 'automatic', jsxImportSource: 'preact', loader: { '.css': 'text' } }),
  ]);

  wr(path.join(OUT, 'content.css'), css.core);
  for (const [id, text] of Object.entries(css.sheets)) wr(path.join(OUT, 'css', `${id}.css`), text);
  const tokens = path.join(ROOT, 'design/spec/tokens.css');
  // UI-only feature styles (options/popup), never content.css.
  const featureUi = fs.readdirSync(path.join(DEV, 'src/features'), { withFileTypes: true })
    .filter(d => d.isDirectory() && fs.existsSync(path.join(DEV, 'src/features', d.name, 'ui.css')))
    .map(d => `/* src/features/${d.name}/ui.css */\n` + rd(path.join(DEV, 'src/features', d.name, 'ui.css')));
  wr(path.join(OUT, 'ui.css'), [fs.existsSync(tokens) ? rd(tokens) : '', rd(path.join(DEV, 'src/ui/shared/ui.css')), ...featureUi].join('\n'));
  wr(path.join(OUT, 'popup.html'), page('b²c', 'popup.js'));
  wr(path.join(OUT, 'options.html'), page('b²c settings', 'options.js'));
  wr(path.join(OUT, 'manifest.json'), JSON.stringify(manifest(version, ids.includes('dark-mode') || ids.includes('palette'), ids.includes('palette') && fs.existsSync(path.join(DEV, 'src/features/palette/docs.ts'))), null, 2));
  await writeSchema(path.join(OUT, 'schema.json'), ids, sheetIds);
  writeIcons();
  // Design's bundled fonts (design/spec/fonts): served to Canvas pages for
  // custom-font and used by the popup/options UI. No third-party requests.
  const fontsDir = path.join(ROOT, 'design/spec/fonts');
  if (fs.existsSync(fontsDir)) {
    fs.mkdirSync(path.join(OUT, 'fonts'), { recursive: true });
    // The OFL notices travel with the fonts.
    for (const f of fs.readdirSync(fontsDir).filter(f => f.endsWith('.woff2') || f.startsWith('LICENSE'))) fs.copyFileSync(path.join(fontsDir, f), path.join(OUT, 'fonts', f));
  }
  // Attribution for bundled third-party theme palettes (MIT/Apache-2.0).
  const themeNotice = path.join(DEV, 'src/core/theme/THEMES-NOTICE.txt');
  if (fs.existsSync(themeNotice)) wr(path.join(OUT, 'licenses/themes.txt'), rd(themeNotice));
  // The settings layout (from design/spec/settings.md) may only name real keys.
  const layoutCheck = path.join(DEV, 'scripts/check-settings-layout.mjs');
  if (fs.existsSync(layoutCheck)) {
    const { checkLayout } = await import(pathToFileURL(layoutCheck).href + `?t=${Date.now()}`);
    // Strict for ships and full builds; a lane's subset build only warns, so
    // one lane renaming a key can't break every other lane's build.
    try {
      await checkLayout(path.join(OUT, 'schema.json'));
    } catch (e) {
      if (!only || process.env.B2C_STRICT_LAYOUT) throw e;
      console.warn(`settings layout (warning in lane builds): ${e.message}`);
    }
  }
  wr(path.join(OUT, 'build-id.txt'), buildId + '\n');

  const bootSize = fs.statSync(path.join(OUT, 'boot.js')).size;
  console.log(`b²c ${buildId} → ${path.relative(process.cwd(), OUT) || '.'}  (${ids.length} features, boot.js ${bootSize} B, ${Math.round(performance.now() - t0)} ms)`);
  return { buildId, out: OUT };
}

