// ui lane: the settings layout may only name real keys (also enforced by the build).
import { describe, expect, it } from 'vitest';
// @ts-expect-error plain .mjs build script
import { validate } from '../../scripts/check-settings-layout.mjs';
import { describe as describeSetting } from '../../src/core/settings/schema.ts';
import { allFeatures, schema } from '../../src/core/registry.ts';
import * as layout from '../../src/ui/shared/layout.ts';

const json = Object.fromEntries(Object.entries(schema).map(([k, s]) => [k, describeSetting(s)]));
type Result = { errors: string[]; warnings: string[] };

describe('settings layout', () => {
  it('names only keys the schema has', () => {
    // Features missing from index.gen.ts (regenerated by full builds only) are skipped, as in a subset build.
    const { errors } = validate(layout, json, new Set(allFeatures.map(f => f.id))) as Result;
    expect(errors).toEqual([]);
  });
  it('fails on a typo, a bad disclosure and duplicate ids; skips other lanes in subset builds', () => {
    const bad = { SECTIONS: [{ id: 's', title: 'S', rows: [
      { id: 'a', key: 'x.enabeld', label: 'A', control: 'switch' },
      { id: 'a', key: 'core.paused', label: 'B', control: 'switch', in: 'nowhere' },
      { id: 'c', key: 'future.enabled', label: 'C', control: 'switch', pending: true },
    ] }] };
    const s = { 'core.paused': { kind: 'bool', default: false } };
    const { errors } = validate(bad, s) as Result;
    expect(errors.join('\n')).toMatch(/x\.enabeld/);
    expect(errors.join('\n')).toMatch(/duplicate row id/);
    expect(errors.join('\n')).toMatch(/no disclosure row "nowhere"/);
    expect(errors.join('\n')).not.toMatch(/future/);
    expect((validate(bad, s, new Set(['y'])) as Result).errors.join('\n')).not.toMatch(/x\.enabeld/);
  });
  it('warns about schema keys the layout does not show', () => {
    const { warnings } = validate({ SECTIONS: [] }, { 'z.new': { kind: 'bool', default: false } }) as Result;
    expect(warnings.join('\n')).toMatch(/z\.new/);
  });
});
